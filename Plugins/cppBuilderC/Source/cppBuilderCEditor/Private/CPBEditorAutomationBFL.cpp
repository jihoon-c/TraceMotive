enum class ECPBEditorAutomationMessageType : uint8
{
	Info,
	Warning,
	Error
};

void CPBReportAutomationMessage(const FString& Message, ECPBEditorAutomationMessageType MessageType)
{
	switch (MessageType)
	{
	case ECPBEditorAutomationMessageType::Info:
		UE_LOG(LogCPBEditorAutomation, Log, TEXT("%s"), *Message);
		break;
	case ECPBEditorAutomationMessageType::Warning:
		UE_LOG(LogCPBEditorAutomation, Warning, TEXT("%s"), *Message);
		break;
	case ECPBEditorAutomationMessageType::Error:
		UE_LOG(LogCPBEditorAutomation, Error, TEXT("%s"), *Message);
		break;
	default:
		UE_LOG(LogCPBEditorAutomation, Log, TEXT("%s"), *Message);
		break;
	}

	if (GEngine)
	{
		const FColor MessageColor = MessageType == ECPBEditorAutomationMessageType::Error
			? FColor::Red
			: MessageType == ECPBEditorAutomationMessageType::Warning
				? FColor::Yellow
				: FColor::Green;

		GEngine->AddOnScreenDebugMessage(-1, 6.0f, MessageColor, Message);
	}
}

