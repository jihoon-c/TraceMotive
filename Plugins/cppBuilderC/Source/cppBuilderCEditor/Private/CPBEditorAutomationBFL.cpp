uint16 CPBReadUInt16(const TArray<uint8>& Data, int64 Offset)
{
	if (!Data.IsValidIndex(Offset + 1))
	{
		return 0;
	}

	return static_cast<uint16>(Data[Offset]) |
		(static_cast<uint16>(Data[Offset + 1]) << 8);
}

uint32 CPBReadUInt32(const TArray<uint8>& Data, int64 Offset)
{
	if (!Data.IsValidIndex(Offset + 3))
	{
		return 0;
	}

	return static_cast<uint32>(Data[Offset]) |
		(static_cast<uint32>(Data[Offset + 1]) << 8) |
		(static_cast<uint32>(Data[Offset + 2]) << 16) |
		(static_cast<uint32>(Data[Offset + 3]) << 24);
}

FString CPBBytesToUtf8String(const TArray<uint8>& Bytes)
{
	if (Bytes.Num() == 0)
	{
		return FString();
	}

	FUTF8ToTCHAR Converter(reinterpret_cast<const ANSICHAR*>(Bytes.GetData()), Bytes.Num());
	return FString(Converter.Length(), Converter.Get());
}

bool CPBInflateRawDeflate(const uint8* CompressedData, int32 CompressedSize, TArray<uint8>& OutUncompressed, int32 UncompressedSize)
{
	OutUncompressed.SetNumUninitialized(UncompressedSize);
	if (UncompressedSize == 0)
	{
		return true;
	}

	z_stream Stream;
	FMemory::Memzero(Stream);
	Stream.next_in = const_cast<Bytef*>(reinterpret_cast<const Bytef*>(CompressedData));
	Stream.avail_in = static_cast<uInt>(CompressedSize);
	Stream.next_out = reinterpret_cast<Bytef*>(OutUncompressed.GetData());
	Stream.avail_out = static_cast<uInt>(UncompressedSize);

	const int32 InitResult = inflateInit2(&Stream, -MAX_WBITS);
	if (InitResult != Z_OK)
	{
		return false;
	}

	const int32 InflateResult = inflate(&Stream, Z_FINISH);
	inflateEnd(&Stream);
	return InflateResult == Z_STREAM_END && Stream.total_out == static_cast<uLong>(UncompressedSize);
}

bool CPBReadZipDirectory(const TArray<uint8>& ZipBytes, TMap<FString, FCPBZipEntryInfo>& OutEntries)
{
	OutEntries.Reset();

	const uint32 EndOfCentralDirectorySignature = 0x06054b50;
	const uint32 CentralDirectoryHeaderSignature = 0x02014b50;
	const int64 MaxSearchBytes = FMath::Min<int64>(ZipBytes.Num(), 65557);

	int64 EndOfCentralDirectoryOffset = INDEX_NONE;
	for (int64 Offset = ZipBytes.Num() - 22; Offset >= ZipBytes.Num() - MaxSearchBytes && Offset >= 0; --Offset)
	{
		if (CPBReadUInt32(ZipBytes, Offset) == EndOfCentralDirectorySignature)
		{
			EndOfCentralDirectoryOffset = Offset;
			break;
		}
	}

	if (EndOfCentralDirectoryOffset == INDEX_NONE)
	{
		return false;
	}

	const uint16 EntryCount = CPBReadUInt16(ZipBytes, EndOfCentralDirectoryOffset + 10);
	const uint32 CentralDirectoryOffset = CPBReadUInt32(ZipBytes, EndOfCentralDirectoryOffset + 16);

	int64 Offset = CentralDirectoryOffset;
	for (uint16 EntryIndex = 0; EntryIndex < EntryCount; ++EntryIndex)
	{
		if (CPBReadUInt32(ZipBytes, Offset) != CentralDirectoryHeaderSignature)
		{
			return false;
		}

		FCPBZipEntryInfo EntryInfo;
		EntryInfo.CompressionMethod = CPBReadUInt16(ZipBytes, Offset + 10);
		EntryInfo.CompressedSize = CPBReadUInt32(ZipBytes, Offset + 20);
		EntryInfo.UncompressedSize = CPBReadUInt32(ZipBytes, Offset + 24);
		const uint16 FileNameLength = CPBReadUInt16(ZipBytes, Offset + 28);
		const uint16 ExtraFieldLength = CPBReadUInt16(ZipBytes, Offset + 30);
		const uint16 CommentLength = CPBReadUInt16(ZipBytes, Offset + 32);
		EntryInfo.LocalHeaderOffset = CPBReadUInt32(ZipBytes, Offset + 42);

		if (!ZipBytes.IsValidIndex(Offset + 46 + FileNameLength - 1))
		{
			return false;
		}

		const TArrayView<const uint8> NameBytes(ZipBytes.GetData() + Offset + 46, FileNameLength);
		EntryInfo.Name = FString(FUTF8ToTCHAR(reinterpret_cast<const ANSICHAR*>(NameBytes.GetData()), NameBytes.Num()).Get());
		EntryInfo.Name.ReplaceInline(TEXT("\\"), TEXT("/"));

		OutEntries.Add(EntryInfo.Name, EntryInfo);
		Offset += 46 + FileNameLength + ExtraFieldLength + CommentLength;
	}

	return true;
}

bool CPBExtractZipEntry(const TArray<uint8>& ZipBytes, const FCPBZipEntryInfo& EntryInfo, TArray<uint8>& OutBytes)
{
	const uint32 LocalHeaderSignature = 0x04034b50;
	const int64 LocalOffset = EntryInfo.LocalHeaderOffset;
	if (CPBReadUInt32(ZipBytes, LocalOffset) != LocalHeaderSignature)
	{
		return false;
	}

	const uint16 FileNameLength = CPBReadUInt16(ZipBytes, LocalOffset + 26);
	const uint16 ExtraFieldLength = CPBReadUInt16(ZipBytes, LocalOffset + 28);
	const int64 DataOffset = LocalOffset + 30 + FileNameLength + ExtraFieldLength;
	if (!ZipBytes.IsValidIndex(DataOffset + EntryInfo.CompressedSize - 1))
	{
		return false;
	}

	const uint8* CompressedData = ZipBytes.GetData() + DataOffset;
	if (EntryInfo.CompressionMethod == 0)
	{
		OutBytes.SetNumUninitialized(EntryInfo.UncompressedSize);
		FMemory::Memcpy(OutBytes.GetData(), CompressedData, EntryInfo.UncompressedSize);
		return true;
	}

	if (EntryInfo.CompressionMethod == 8)
	{
		return CPBInflateRawDeflate(CompressedData, EntryInfo.CompressedSize, OutBytes, EntryInfo.UncompressedSize);
	}

	return false;
}

bool CPBReadXlsxTextEntry(
	const TArray<uint8>& XlsxBytes,
	const TMap<FString, FCPBZipEntryInfo>& ZipEntries,
	const FString& EntryPath,
	FString& OutText)
{
	const FCPBZipEntryInfo* EntryInfo = ZipEntries.Find(EntryPath);
	if (!EntryInfo)
	{
		return false;
	}

	TArray<uint8> EntryBytes;
	if (!CPBExtractZipEntry(XlsxBytes, *EntryInfo, EntryBytes))
	{
		return false;
	}

	OutText = CPBBytesToUtf8String(EntryBytes);
	return true;
}

const FXmlNode* CPBFindXmlChildByTag(const FXmlNode* Node, const FString& Tag)
{
	if (!Node)
	{
		return nullptr;
	}

	for (const FXmlNode* Child : Node->GetChildrenNodes())
	{
		if (Child && Child->GetTag().Equals(Tag, ESearchCase::IgnoreCase))
		{
			return Child;
		}
	}

	return nullptr;
}

void CPBCollectXmlTextNodes(const FXmlNode* Node, FString& InOutText)
{
	if (!Node)
	{
		return;
	}

	if (Node->GetTag().Equals(TEXT("t"), ESearchCase::IgnoreCase))
	{
		InOutText += Node->GetContent();
	}

	for (const FXmlNode* Child : Node->GetChildrenNodes())
	{
		CPBCollectXmlTextNodes(Child, InOutText);
	}
}

bool CPBParseSharedStringsXml(const FString& SharedStringsXml, TArray<FString>& OutSharedStrings)
{
	OutSharedStrings.Reset();

	if (SharedStringsXml.IsEmpty())
	{
		return true;
	}

	FXmlFile XmlFile(SharedStringsXml, EConstructMethod::ConstructFromBuffer);
	if (!XmlFile.IsValid() || !XmlFile.GetRootNode())
	{
		return false;
	}

	for (const FXmlNode* SharedStringNode : XmlFile.GetRootNode()->GetChildrenNodes())
	{
		if (!SharedStringNode || !SharedStringNode->GetTag().Equals(TEXT("si"), ESearchCase::IgnoreCase))
		{
			continue;
		}

		FString Text;
		CPBCollectXmlTextNodes(SharedStringNode, Text);
		OutSharedStrings.Add(Text);
	}

	return true;
}

int32 CPBColumnIndexFromCellReference(const FString& CellReference)
{
	int32 ColumnIndex = 0;
	for (int32 CharIndex = 0; CharIndex < CellReference.Len(); ++CharIndex)
	{
		const TCHAR Character = CellReference[CharIndex];
		if (!FChar::IsAlpha(Character))
		{
			break;
		}

		ColumnIndex = ColumnIndex * 26 + (FChar::ToUpper(Character) - TEXT('A') + 1);
	}

	return ColumnIndex > 0 ? ColumnIndex - 1 : INDEX_NONE;
}

FString CPBGetXlsxCellText(const FXmlNode* CellNode, const TArray<FString>& SharedStrings)
{
	if (!CellNode)
	{
		return FString();
	}

	const FString CellType = CellNode->GetAttribute(TEXT("t"));
	if (CellType.Equals(TEXT("inlineStr"), ESearchCase::IgnoreCase))
	{
		if (const FXmlNode* InlineStringNode = CPBFindXmlChildByTag(CellNode, TEXT("is")))
		{
			FString InlineText;
			CPBCollectXmlTextNodes(InlineStringNode, InlineText);
			return InlineText;
		}

		return FString();
	}

	const FXmlNode* ValueNode = CPBFindXmlChildByTag(CellNode, TEXT("v"));
	const FString RawValue = ValueNode ? ValueNode->GetContent() : FString();

	if (CellType.Equals(TEXT("s"), ESearchCase::IgnoreCase))
	{
		const int32 SharedStringIndex = FCString::Atoi(*RawValue);
		return SharedStrings.IsValidIndex(SharedStringIndex) ? SharedStrings[SharedStringIndex] : FString();
	}

	if (CellType.Equals(TEXT("b"), ESearchCase::IgnoreCase))
	{
		return RawValue == TEXT("1") ? TEXT("TRUE") : TEXT("FALSE");
	}

	return RawValue;
}

bool CPBParseWorksheetXml(const FString& SheetXml, const TArray<FString>& SharedStrings, TArray<TArray<FString>>& OutRows)
{
	OutRows.Reset();

	FXmlFile XmlFile(SheetXml, EConstructMethod::ConstructFromBuffer);
	if (!XmlFile.IsValid() || !XmlFile.GetRootNode())
	{
		return false;
	}

	const FXmlNode* SheetDataNode = CPBFindXmlChildByTag(XmlFile.GetRootNode(), TEXT("sheetData"));
	if (!SheetDataNode)
	{
		return false;
	}

	for (const FXmlNode* RowNode : SheetDataNode->GetChildrenNodes())
	{
		if (!RowNode || !RowNode->GetTag().Equals(TEXT("row"), ESearchCase::IgnoreCase))
		{
			continue;
		}

		TArray<FString> RowValues;
		int32 NextColumnIndex = 0;

		for (const FXmlNode* CellNode : RowNode->GetChildrenNodes())
		{
			if (!CellNode || !CellNode->GetTag().Equals(TEXT("c"), ESearchCase::IgnoreCase))
			{
				continue;
			}

			int32 ColumnIndex = CPBColumnIndexFromCellReference(CellNode->GetAttribute(TEXT("r")));
			if (ColumnIndex == INDEX_NONE)
			{
				ColumnIndex = NextColumnIndex;
			}

			while (RowValues.Num() <= ColumnIndex)
			{
				RowValues.Add(FString());
			}

			RowValues[ColumnIndex] = CPBGetXlsxCellText(CellNode, SharedStrings);
			NextColumnIndex = ColumnIndex + 1;
		}

		OutRows.Add(RowValues);
	}

	return true;
}

bool CPBParseWorkbookSheets(
	const FString& WorkbookXml,
	const FString& WorkbookRelationshipsXml,
	TArray<FCPBXlsxSheetInfo>& OutSheets)
{
	OutSheets.Reset();

	FXmlFile WorkbookFile(WorkbookXml, EConstructMethod::ConstructFromBuffer);
	FXmlFile RelationshipsFile(WorkbookRelationshipsXml, EConstructMethod::ConstructFromBuffer);
	if (!WorkbookFile.IsValid() || !RelationshipsFile.IsValid() || !WorkbookFile.GetRootNode() || !RelationshipsFile.GetRootNode())
	{
		return false;
	}

	TMap<FString, FString> RelationshipTargets;
	for (const FXmlNode* RelationshipNode : RelationshipsFile.GetRootNode()->GetChildrenNodes())
	{
		if (!RelationshipNode || !RelationshipNode->GetTag().Equals(TEXT("Relationship"), ESearchCase::IgnoreCase))
		{
			continue;
		}

		FString Target = RelationshipNode->GetAttribute(TEXT("Target"));
		Target.ReplaceInline(TEXT("\\"), TEXT("/"));
		if (Target.StartsWith(TEXT("/")))
		{
			Target.RightChopInline(1);
		}
		else
		{
			Target = TEXT("xl/") + Target;
		}

		RelationshipTargets.Add(RelationshipNode->GetAttribute(TEXT("Id")), Target);
	}

	const FXmlNode* SheetsNode = CPBFindXmlChildByTag(WorkbookFile.GetRootNode(), TEXT("sheets"));
	if (!SheetsNode)
	{
		return false;
	}

	for (const FXmlNode* SheetNode : SheetsNode->GetChildrenNodes())
	{
		if (!SheetNode || !SheetNode->GetTag().Equals(TEXT("sheet"), ESearchCase::IgnoreCase))
		{
			continue;
		}

		FCPBXlsxSheetInfo SheetInfo;
		SheetInfo.Name = SheetNode->GetAttribute(TEXT("name"));
		SheetInfo.RelationshipId = SheetNode->GetAttribute(TEXT("r:id"));
		if (const FString* TargetPath = RelationshipTargets.Find(SheetInfo.RelationshipId))
		{
			SheetInfo.Path = *TargetPath;
			OutSheets.Add(SheetInfo);
		}
	}

	return OutSheets.Num() > 0;
}

bool CPBLoadXlsxSheets(const FString& ExcelFilePath, TMap<FString, TArray<TArray<FString>>>& OutSheets)
{
	OutSheets.Reset();

	TArray<uint8> XlsxBytes;
	if (!FFileHelper::LoadFileToArray(XlsxBytes, *ExcelFilePath))
	{
		CPBReportAutomationMessage(
			FString::Printf(TEXT("CPB Excel automation failed: cannot read '%s'."), *ExcelFilePath),
			ECPBEditorAutomationMessageType::Error);
		return false;
	}

	TMap<FString, FCPBZipEntryInfo> ZipEntries;
	if (!CPBReadZipDirectory(XlsxBytes, ZipEntries))
	{
		CPBReportAutomationMessage(TEXT("CPB Excel automation failed: invalid .xlsx ZIP directory."), ECPBEditorAutomationMessageType::Error);
		return false;
	}

	FString WorkbookXml;
	FString RelationshipsXml;
	if (!CPBReadXlsxTextEntry(XlsxBytes, ZipEntries, TEXT("xl/workbook.xml"), WorkbookXml) ||
		!CPBReadXlsxTextEntry(XlsxBytes, ZipEntries, TEXT("xl/_rels/workbook.xml.rels"), RelationshipsXml))
	{
		CPBReportAutomationMessage(TEXT("CPB Excel automation failed: workbook metadata is missing."), ECPBEditorAutomationMessageType::Error);
		return false;
	}

	TArray<FString> SharedStrings;
	FString SharedStringsXml;
	if (CPBReadXlsxTextEntry(XlsxBytes, ZipEntries, TEXT("xl/sharedStrings.xml"), SharedStringsXml))
	{
		if (!CPBParseSharedStringsXml(SharedStringsXml, SharedStrings))
		{
			CPBReportAutomationMessage(TEXT("CPB Excel automation failed: shared strings could not be parsed."), ECPBEditorAutomationMessageType::Error);
			return false;
		}
	}

	TArray<FCPBXlsxSheetInfo> SheetInfos;
	if (!CPBParseWorkbookSheets(WorkbookXml, RelationshipsXml, SheetInfos))
	{
		CPBReportAutomationMessage(TEXT("CPB Excel automation failed: workbook sheet list could not be parsed."), ECPBEditorAutomationMessageType::Error);
		return false;
	}

	for (const FCPBXlsxSheetInfo& SheetInfo : SheetInfos)
	{
		FString SheetXml;
		if (!CPBReadXlsxTextEntry(XlsxBytes, ZipEntries, SheetInfo.Path, SheetXml))
		{
			CPBReportAutomationMessage(
				FString::Printf(TEXT("CPB Excel automation warning: sheet '%s' XML was not found."), *SheetInfo.Name),
				ECPBEditorAutomationMessageType::Warning);
			continue;
		}

		TArray<TArray<FString>> SheetRows;
		if (CPBParseWorksheetXml(SheetXml, SharedStrings, SheetRows))
		{
			OutSheets.Add(SheetInfo.Name, MoveTemp(SheetRows));
		}
	}

	return OutSheets.Num() > 0;
}

FString CPBMakeCsvCell(const FString& InValue)
{
	FString Value = InValue;
	Value.ReplaceInline(TEXT("\""), TEXT("\"\""));

	if (Value.Contains(TEXT(",")) || Value.Contains(TEXT("\"")) || Value.Contains(TEXT("\n")) || Value.Contains(TEXT("\r")))
	{
		return FString::Printf(TEXT("\"%s\""), *Value);
	}

	return Value;
}

bool CPBWriteRowsToCsv(const TArray<TArray<FString>>& Rows, const FString& CsvFilePath)
{
	TArray<FString> Lines;
	Lines.Reserve(Rows.Num());

	for (const TArray<FString>& Row : Rows)
	{
		TArray<FString> Cells;
		Cells.Reserve(Row.Num());
		for (const FString& Cell : Row)
		{
			Cells.Add(CPBMakeCsvCell(Cell));
		}

		Lines.Add(FString::Join(Cells, TEXT(",")));
	}

	return FFileHelper::SaveStringToFile(
		FString::Join(Lines, TEXT("\n")),
		*CsvFilePath,
		FFileHelper::EEncodingOptions::ForceUTF8WithoutBOM);
}

bool CPBConvertXlsxToMasterCsvFolder(const FString& ExcelFilePath, FString& OutCsvFolderPath)
{
	const FString FullExcelFilePath = FPaths::ConvertRelativePathToFull(ExcelFilePath);
	if (!FPaths::FileExists(FullExcelFilePath))
	{
		CPBReportAutomationMessage(
			FString::Printf(TEXT("CPB Excel automation failed: Excel file does not exist at '%s'."), *FullExcelFilePath),
			ECPBEditorAutomationMessageType::Error);
		return false;
	}

	TMap<FString, TArray<TArray<FString>>> Sheets;
	if (!CPBLoadXlsxSheets(FullExcelFilePath, Sheets))
	{
		return false;
	}

	const FString WorkbookBaseName = FPaths::GetBaseFilename(FullExcelFilePath);
	OutCsvFolderPath = FPaths::Combine(FPaths::ProjectSavedDir(), TEXT("CPBMasterExcelCache"), WorkbookBaseName);
	IFileManager::Get().MakeDirectory(*OutCsvFolderPath, true);

	static const TArray<FString> RequiredSheetNames =
	{
		TEXT("Set_Level"),
		TEXT("DT_ScenarioFlow"),
		TEXT("DT_ActionEvent"),
		TEXT("DT_Dictionary")
	};

	bool bWroteRequiredSheets = true;
	for (const FString& SheetName : RequiredSheetNames)
	{
		const TArray<TArray<FString>>* Rows = Sheets.Find(SheetName);
		if (!Rows)
		{
			bWroteRequiredSheets = false;
			CPBReportAutomationMessage(
				FString::Printf(TEXT("CPB Excel automation warning: required sheet '%s' was not found in '%s'."), *SheetName, *FullExcelFilePath),
				ECPBEditorAutomationMessageType::Warning);
			continue;
		}

		const FString CsvFilePath = FPaths::Combine(OutCsvFolderPath, SheetName + TEXT(".csv"));
		if (!CPBWriteRowsToCsv(*Rows, CsvFilePath))
		{
			bWroteRequiredSheets = false;
			CPBReportAutomationMessage(
				FString::Printf(TEXT("CPB Excel automation failed: could not write temporary CSV '%s'."), *CsvFilePath),
				ECPBEditorAutomationMessageType::Error);
		}
	}

	return bWroteRequiredSheets;
}

