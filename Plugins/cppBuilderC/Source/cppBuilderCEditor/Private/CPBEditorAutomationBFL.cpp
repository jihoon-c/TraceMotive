bool UCPBEditorAutomationBFL::AutoGenerateSequencesFromDataTables(UDataTable* ScenarioFlowTable, UDataTable* ActionEventTable)
{
	if (!ScenarioFlowTable || ScenarioFlowTable->GetRowStruct() != FCPBScenarioFlowDTO::StaticStruct())
	{
		CPBReportAutomationMessage(TEXT("CPB sequence generation failed: ScenarioFlowTable must use FCPBScenarioFlowDTO."), ECPBEditorAutomationMessageType::Error);
		return false;
	}

	if (!ActionEventTable || ActionEventTable->GetRowStruct() != FCPBActionEventDTO::StaticStruct())
	{
		CPBReportAutomationMessage(TEXT("CPB sequence generation failed: ActionEventTable must use FCPBActionEventDTO."), ECPBEditorAutomationMessageType::Error);
		return false;
	}

	if (!GEditor)
	{
		CPBReportAutomationMessage(TEXT("CPB sequence generation failed: GEditor is unavailable."), ECPBEditorAutomationMessageType::Error);
		return false;
	}

	UWorld* World = GEditor->GetEditorWorldContext().World();
	if (!World)
	{
		CPBReportAutomationMessage(TEXT("CPB sequence generation failed: Editor world is unavailable."), ECPBEditorAutomationMessageType::Error);
		return false;
	}

	if (World->IsPlayInEditor() || GEditor->PlayWorld)
	{
		CPBReportAutomationMessage(TEXT("CPB sequence generation aborted: sequence actor spawning is disabled while Play In Editor is active."), ECPBEditorAutomationMessageType::Warning);
		return false;
	}

	ACPBSequenceManager* SequenceManager = CPBFindOrSpawnSequenceManager(World);
	if (!SequenceManager)
	{
		CPBReportAutomationMessage(TEXT("CPB sequence generation failed: could not find or spawn ACPBSequenceManager."), ECPBEditorAutomationMessageType::Error);
		return false;
	}

	UClass* SequenceClass = CPBResolveActorClass(TEXT("ACPBSequence"));
	if (!SequenceClass || !SequenceClass->IsChildOf(ACPBSequence::StaticClass()))
	{
		CPBReportAutomationMessage(TEXT("CPB sequence generation failed: could not resolve ACPBSequence class."), ECPBEditorAutomationMessageType::Error);
		return false;
	}

	TArray<FCPBScenarioFlowDTO> ScenarioRows;
	for (const TPair<FName, uint8*>& RowPair : ScenarioFlowTable->GetRowMap())
	{
		const FCPBScenarioFlowDTO* Row = reinterpret_cast<const FCPBScenarioFlowDTO*>(RowPair.Value);
		if (Row && !Row->SequenceId.IsNone())
		{
			ScenarioRows.Add(*Row);
		}
	}

	ScenarioRows.Sort([](const FCPBScenarioFlowDTO& Left, const FCPBScenarioFlowDTO& Right)
	{
		if (Left.PhaseId == Right.PhaseId)
		{
			return Left.StepOrder < Right.StepOrder;
		}

		return Left.PhaseId.LexicalLess(Right.PhaseId);
	});

	TMultiMap<FName, FCPBActionEventDTO> EventsBySequence;
	for (const TPair<FName, uint8*>& RowPair : ActionEventTable->GetRowMap())
	{
		const FCPBActionEventDTO* Row = reinterpret_cast<const FCPBActionEventDTO*>(RowPair.Value);
		if (Row && !Row->OwnerSequence.IsNone())
		{
			EventsBySequence.Add(Row->OwnerSequence, *Row);
		}
	}

	const FScopedTransaction Transaction(NSLOCTEXT("CPBEditorAutomation", "AutoGenerateSequencesFromDataTables", "Auto Generate CPB Sequences From DataTables"));
	World->Modify();
	SequenceManager->Modify();

	int32 SpawnedSequenceCount = 0;
	int32 WarningCount = 0;

	for (const FCPBScenarioFlowDTO& ScenarioRow : ScenarioRows)
	{
		FActorSpawnParameters SpawnParameters;
		SpawnParameters.SpawnCollisionHandlingOverride = ESpawnActorCollisionHandlingMethod::AlwaysSpawn;
		SpawnParameters.ObjectFlags |= RF_Transactional;

		const FVector SpawnLocation = SequenceManager->GetActorLocation() + FVector(0.0f, SpawnedSequenceCount * 40.0f, 0.0f);
		ACPBSequence* Sequence = World->SpawnActor<ACPBSequence>(SequenceClass, SpawnLocation, SequenceManager->GetActorRotation(), SpawnParameters);
		if (!Sequence)
		{
			++WarningCount;
			CPBReportAutomationMessage(
				FString::Printf(TEXT("CPB sequence generation failed: could not spawn sequence '%s'."), *ScenarioRow.SequenceId.ToString()),
				ECPBEditorAutomationMessageType::Warning);
			continue;
		}

		Sequence->SetActorLabel(ScenarioRow.SequenceId.ToString());
		Sequence->Tags.AddUnique(CPBAutoGeneratedActorTag);
		Sequence->Tags.AddUnique(CPBAutomationSystemTag);
		Sequence->Tags.Add(ScenarioRow.SequenceId);
		Sequence->Tags.Add(ScenarioRow.PhaseId);

		CPBSetFNameProperty(Sequence, TEXT("SequenceId"), ScenarioRow.SequenceId);
		CPBSetFTextProperty(Sequence, TEXT("DisplayName"), FText::FromName(ScenarioRow.SequenceId));
		CPBSetIntProperty(Sequence, TEXT("SortOrder"), SpawnedSequenceCount);

		FCPBSequenceStep Step;
		Step.StepId = ScenarioRow.SequenceId;
		Step.CameraViewId = ScenarioRow.TargetViewTag;
		Step.ViewTransition = ECPBViewTransition::Fade;
		Step.FadeDuration = 0.25f;

		TArray<FCPBActionEventDTO> SequenceEvents;
		EventsBySequence.MultiFind(ScenarioRow.SequenceId, SequenceEvents);
		SequenceEvents.Sort([](const FCPBActionEventDTO& Left, const FCPBActionEventDTO& Right)
		{
			return Left.Time < Right.Time;
		});

		for (const FCPBActionEventDTO& EventRow : SequenceEvents)
		{
			Step.AnimationLength = FMath::Max(Step.AnimationLength, EventRow.Time);

			if (EventRow.ActionType == FName(TEXT("HideActor")) || EventRow.ActionType == FName(TEXT("ShowActor")))
			{
				AActor* TargetActor = CPBFindActorByTag(World, EventRow.TargetTag);
				if (!TargetActor)
				{
					++WarningCount;
					CPBReportAutomationMessage(
						FString::Printf(TEXT("CPB sequence '%s': target actor tag '%s' for event '%s' was not found."),
							*ScenarioRow.SequenceId.ToString(),
							*EventRow.TargetTag.ToString(),
							*EventRow.EventId.ToString()),
						ECPBEditorAutomationMessageType::Warning);
					continue;
				}

				if (EventRow.ActionType == FName(TEXT("HideActor")))
				{
					Step.HidingActors.AddUnique(TargetActor);
				}
				else
				{
					Step.UnhidingActors.AddUnique(TargetActor);
				}
			}
		}

		if (!CPBSetSequenceSteps(Sequence, { Step }))
		{
			++WarningCount;
			CPBReportAutomationMessage(
				FString::Printf(TEXT("CPB sequence '%s': failed to set generated step data."), *ScenarioRow.SequenceId.ToString()),
				ECPBEditorAutomationMessageType::Warning);
		}

		if (AActor* TargetInteractor = CPBFindActorByTag(World, ScenarioRow.TargetInteractorTag))
		{
			CPBSetFNameProperty(TargetInteractor, TEXT("AssemblyId"), ScenarioRow.SequenceId);

			if (!ScenarioRow.RequiredToolName.IsNone())
			{
				TargetInteractor->Tags.AddUnique(ScenarioRow.RequiredToolName);
			}

			if (!ScenarioRow.InteractionType.IsNone())
			{
				TargetInteractor->Tags.AddUnique(ScenarioRow.InteractionType);
			}
		}
		else if (!ScenarioRow.TargetInteractorTag.IsNone())
		{
			++WarningCount;
			CPBReportAutomationMessage(
				FString::Printf(TEXT("CPB sequence '%s': TargetInteractorTag '%s' was not found."),
					*ScenarioRow.SequenceId.ToString(),
					*ScenarioRow.TargetInteractorTag.ToString()),
				ECPBEditorAutomationMessageType::Warning);
		}

		SequenceManager->RegisterSequence(Sequence);
		++SpawnedSequenceCount;
	}

	SequenceManager->SortRegisteredSequencesBySortOrder();
	World->MarkPackageDirty();

	CPBReportAutomationMessage(
		FString::Printf(TEXT("CPB sequence generation completed: %d sequence actors created, %d warnings."), SpawnedSequenceCount, WarningCount),
		WarningCount > 0 ? ECPBEditorAutomationMessageType::Warning : ECPBEditorAutomationMessageType::Info);

	return SpawnedSequenceCount > 0;
}

bool UCPBEditorAutomationBFL::RunMasterAutomationFromCSVFolder(
	const FString& CsvFolderPath,
	const FString& DestinationAssetFolder,
	const FString& NarrationAssetRootPath)
{
	FCPBGeneratedDataTables GeneratedTables;
	if (!CPBBuildGeneratedDataTables(CsvFolderPath, DestinationAssetFolder, NarrationAssetRootPath, GeneratedTables))
	{
		return false;
	}

	ClearAutoGeneratedLevelActors();

	const bool bGeneratedLevel = AutoGenerateLevelFromDataTable(GeneratedTables.LevelPlacementTable);
	const bool bGeneratedSequences = AutoGenerateSequencesFromDataTables(GeneratedTables.ScenarioFlowTable, GeneratedTables.ActionEventTable);

	CPBReportAutomationMessage(
		FString::Printf(TEXT("CPB master automation completed: level=%s, sequences=%s, generated DataTables='%s'."),
			bGeneratedLevel ? TEXT("OK") : TEXT("Failed"),
			bGeneratedSequences ? TEXT("OK") : TEXT("Failed"),
			*DestinationAssetFolder),
		(bGeneratedLevel && bGeneratedSequences) ? ECPBEditorAutomationMessageType::Info : ECPBEditorAutomationMessageType::Warning);

	return bGeneratedLevel && bGeneratedSequences;
}

